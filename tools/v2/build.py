"""Build all v2 layers: SVG -> PNG (Chromium) -> styled raster (paint2.py).
Usage: python3 tools/v2/build.py [world ...] [--only name,name] [--raw DIR]
Writes v2/assets/img/*.webp and v2/js/assets.js (natural sizes + styles)."""
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
args = sys.argv[1:]
raw = '/tmp/ke-v2-raw'
if '--raw' in args:
    raw = args[args.index('--raw') + 1]
only = set()
if '--only' in args:
    only = set(args[args.index('--only') + 1].split(','))
skip = {args[i + 1] for i, a in enumerate(args) if a in ('--only', '--raw') and i + 1 < len(args)}
worlds = [a for a in args if not a.startswith('--') and a not in skip] or ['home']
os.makedirs(raw, exist_ok=True)
reg_path = os.path.join(ROOT, 'v2', 'js', 'assets.js')
reg = {}
if os.path.exists(reg_path):
    txt = open(reg_path).read()
    reg = json.loads(txt[txt.index('{'):txt.rindex('}') + 1])
layers = {}
for w in worlds:
    mod = __import__(w)
    layers.update(mod.build())
todo = [n for n in layers if not only or n in only]
svgs = [os.path.join(HERE, 'svg', n + '.svg') for n in todo]
for i in range(0, len(svgs), 12):
    subprocess.run(['node', os.path.join(ROOT, 'tools', 'render_svg.mjs'), raw] + svgs[i:i + 12], check=True, stdout=subprocess.DEVNULL)


def paint(n):
    L = layers[n]
    cmd = ['python3', os.path.join(HERE, 'paint2.py'), os.path.join(raw, n + '.png'), os.path.join(ROOT, 'v2', 'assets', 'img', n + '.webp'),
           '--style', L.get('style', 'warm'), '--border', str(L.get('border', 0)), '--scale', str(L.get('scale', max(L['w'], L['h']) / 1920 if L.get('style') != 'halftone' else 1)),
           '--quality', str(L.get('quality', 80))]
    if L.get('tint'):
        cmd += ['--tint', L['tint']]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
    return n


with ThreadPoolExecutor(4) as ex:
    for n in ex.map(paint, todo):
        print('ok', n)
from PIL import Image
for n, L in layers.items():
    f = os.path.join(ROOT, 'v2', 'assets', 'img', n + '.webp')
    reg[n] = list(Image.open(f).size) if os.path.exists(f) else [L['w'], L['h']]
with open(reg_path, 'w') as f:
    f.write('/* generated by tools/v2/build.py: natural pixel sizes of every layer */\nwindow.ASSETS = ' + json.dumps(reg, indent=0) + ';\n')
print('assets registered', len(reg))
